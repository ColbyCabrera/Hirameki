#!/usr/bin/env python3
"""Rebuild Hirameki's translations from upstream AnkiDroid's community translations.

Upstream AnkiDroid translates on Crowdin and commits the results to its main branch. Most of
Hirameki's English strings are still identical to upstream's, so those translations stay valid.
This script copies them in, but only where the translation still describes Hirameki's English.

For each locale, a translation is taken from the first source (see --source) where:
  * Hirameki still has a translatable string with that name and type,
  * the source's English text matches Hirameki's (ignoring case, whitespace and quote style;
    pass --strict to require an exact match), or differs only by "AnkiDroid" -> "Hirameki"
    and the translation spells AnkiDroid in Latin script, in which case it is renamed too,
  * the translation is not just a copy of the English (Crowdin's export of an untranslated
    string), and
  * it uses the same format arguments as Hirameki's English, since a mismatch crashes at
    runtime.

Each values-<locale>/ folder then holds two kinds of file:
  * NN-name.xml       Generated by this script. Never edit them, the next sync overwrites them.
  * everything else   Hirameki's own translations, which this script never overwrites:
      strings.xml     Hirameki-only strings.
      overrides.xml   Corrections and translations of upstream strings. These win over upstream.
      ai-fill.xml     Unreviewed machine translations. Once upstream translates one of these
                      strings, upstream wins and the entry is removed from this file.

Android rejects a string defined twice in one folder, so the generated files leave out every
string that a local file defines.

Usage (from the repository root, after `git fetch upstream`):
  python tools/localization/sync_upstream_translations.py --locale fa             # dry run
  python tools/localization/sync_upstream_translations.py --locale fa --write
  python tools/localization/sync_upstream_translations.py --all --write
  python tools/localization/sync_upstream_translations.py --locale fa --list-missing
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FORK_RES = "AnkiDroid/src/main/res"
UPSTREAM_REF = "upstream/main"
UPSTREAM_RES = "common/android/src/main/res"

GENERATED_FILE = re.compile(r"^\d\d-[\w-]+\.xml$")
NOT_TRANSLATED_FILES = {"12-dont-translate.xml"}
HIRAMEKI_FILE = "strings.xml"
AI_FILL_FILE = "ai-fill.xml"

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
  ~ GENERATED by tools/localization/sync_upstream_translations.py. DO NOT EDIT.
  ~
  ~ These are AnkiDroid's community translations (https://crowdin.com/project/ankidroid),
  ~ keeping only the strings whose English is still the same in Hirameki.
  ~ To correct or add a translation, put it in overrides.xml in this folder;
  ~ Hirameki-only strings go in strings.xml. See tools/localization/README.md.
  -->
"""

RESOURCE = re.compile(
    r"""<(?P<tag>string|plurals|string-array)\b"""
    r"""(?P<attrs>(?:\s+[\w:.-]+\s*=\s*(?:"[^"]*"|'[^']*'))*)\s*"""
    r"""(?:/>|>(?P<body>.*?)</(?P=tag)\s*>)""",
    re.S,
)
ATTRIBUTE = re.compile(r"""([\w:.-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')""")
COMMENT = re.compile(r"<!--.*?-->", re.S)
# Flags exclude the space flag, so that "100% done" is not read as "% d".
FORMAT_ARGUMENT = re.compile(r"%(?:(\d+)\$)?[-#+0,(<]*\d*(?:\.\d+)?([a-zA-Z%])")


@dataclass
class Resource:
    tag: str
    name: str
    body: str
    start: int
    end: int
    raw: str
    attrs: dict[str, str]

    @property
    def translatable(self) -> bool:
        return self.attrs.get("translatable") != "false"


def parse_resources(text: str) -> list[Resource]:
    """Finds the top-level string resources, keeping their exact source text and position."""
    # Blank out comments so commented-out resources are ignored, without moving any offsets.
    searchable = COMMENT.sub(lambda m: re.sub(r"\S", " ", m.group()), text)
    resources = []
    for match in RESOURCE.finditer(searchable):
        attrs = {m[1]: m[2] if m[2] is not None else m[3] for m in ATTRIBUTE.finditer(match["attrs"])}
        if "name" not in attrs:
            continue
        start, end = match.span()
        body_start, body_end = match.span("body") if match["body"] is not None else (end, end)
        resources.append(
            Resource(
                tag=match["tag"],
                name=attrs["name"],
                body=text[body_start:body_end],
                start=start,
                end=end,
                raw=text[start:end],
                attrs=attrs,
            )
        )
    return resources


def normalize(body: str, strict: bool) -> str:
    text = re.sub(r"\s+", " ", body).strip()
    if strict:
        return text
    text = re.sub(r"(?:\\n|\s)+", " ", text).strip()
    for before, after in (("\\'", "'"), ("‘", "'"), ("’", "'"), ('\\"', '"'),
                          ("“", '"'), ("”", '"'), ("…", "...")):
        text = text.replace(before, after)
    return text.casefold()


def format_arguments(body: str) -> set[tuple[int, str]]:
    arguments = set()
    position = 0
    for match in FORMAT_ARGUMENT.finditer(body):
        conversion = match[2]
        if conversion in "%n":
            continue
        if match[1]:
            index = int(match[1])
        else:
            position += 1
            index = position
        arguments.add((index, conversion.lower()))
    return arguments


def plural_items(body: str) -> list[str]:
    return re.findall(r"<item\b[^>]*>(.*?)</item\s*>", body, re.S) or [body]


def format_problem(english: Resource, translation_body: str) -> str | None:
    if english.attrs.get("formatted") == "false" or english.tag == "string-array":
        return None
    expected = format_arguments(english.body)
    if english.tag == "plurals":
        # A quantity may leave out the number ("one" is often written as a word), but must not add arguments.
        for item in plural_items(translation_body):
            if not format_arguments(item) <= expected:
                return f"uses {sorted(format_arguments(item))}, English has {sorted(expected)}"
        return None
    actual = format_arguments(translation_body)
    if actual != expected:
        return f"uses {sorted(actual)}, English has {sorted(expected)}"
    return None


class Git:
    """Reads files from any commit through one `git cat-file --batch` process."""

    def __init__(self) -> None:
        self.process = subprocess.Popen(
            ["git", "cat-file", "--batch"], cwd=REPO, stdin=subprocess.PIPE, stdout=subprocess.PIPE
        )

    def read(self, commit: str, path: str) -> str | None:
        assert self.process.stdin and self.process.stdout
        self.process.stdin.write(f"{commit}:{path}\n".encode())
        self.process.stdin.flush()
        header = self.process.stdout.readline().decode().split()
        if len(header) != 3:
            return None  # "<object> missing"
        content = self.process.stdout.read(int(header[2]))
        self.process.stdout.read(1)  # trailing newline
        return content.decode("utf-8") if header[1] == "blob" else None

    @staticmethod
    def resolve(ref: str) -> str:
        return run_git("rev-parse", "--verify", f"{ref}^{{commit}}")

    @staticmethod
    def list_files(commit: str, directory: str) -> list[str]:
        output = run_git("ls-tree", "--name-only", commit, f"{directory}/")
        return [line.rsplit("/", 1)[-1] for line in output.splitlines()]


def run_git(*args: str) -> str:
    result = subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed:\n{result.stderr.strip()}")
    return result.stdout.strip()


@dataclass
class Source:
    """A commit and resource folder holding upstream English and translations."""

    label: str
    commit: str
    res: str
    git: Git
    _english: dict[str, Resource] | None = None

    def english(self) -> dict[str, Resource]:
        if self._english is None:
            self._english = {}
            for file in self.translated_files("values"):
                for resource in parse_resources(self.git.read(self.commit, f"{self.res}/values/{file}") or ""):
                    self._english.setdefault(resource.name, resource)
        return self._english

    def translated_files(self, folder: str) -> list[str]:
        files = Git.list_files(self.commit, f"{self.res}/{folder}")
        return [f for f in files if GENERATED_FILE.match(f) and f not in NOT_TRANSLATED_FILES]

    def locale_files(self, locale: str) -> dict[str, str]:
        folder = f"values-{locale}"
        return {
            file: self.git.read(self.commit, f"{self.res}/{folder}/{file}") or ""
            for file in self.translated_files(folder)
        }


@dataclass
class Choice:
    source: int
    file: str
    resource: Resource
    raw: str  # possibly renamed to Hirameki
    note: str  # "exact", "fuzzy" or "renamed"


@dataclass
class LocaleResult:
    locale: str
    outputs: dict[str, str] = field(default_factory=dict)
    removed_files: list[str] = field(default_factory=list)
    ai_fill_text: str | None = None
    choices: dict[str, Choice] = field(default_factory=dict)
    skipped: dict[str, dict[str, str]] = field(default_factory=dict)  # reason -> name -> detail
    superseded_ai_fill: list[str] = field(default_factory=list)
    before: dict[str, str] = field(default_factory=dict)
    local_keys: dict[str, str] = field(default_factory=dict)
    missing: list[str] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)

    def skip(self, reason: str, name: str, detail: str = "") -> None:
        self.skipped.setdefault(reason, {})[name] = detail


def load_fork_english() -> tuple[dict[str, Resource], set[str]]:
    """All translatable English strings, and the names a translator is expected to cover."""
    english: dict[str, Resource] = {}
    expected: set[str] = set()
    for path in sorted((REPO / FORK_RES / "values").glob("*.xml")):
        for resource in parse_resources(path.read_text(encoding="utf-8")):
            if not resource.translatable:
                continue
            english[resource.name] = resource
            if path.name == HIRAMEKI_FILE or (GENERATED_FILE.match(path.name) and path.name not in NOT_TRANSLATED_FILES):
                expected.add(resource.name)
    return english, expected


def choose(
    name: str,
    fork: Resource,
    sources: list[Source],
    translations: list[dict[str, tuple[str, Resource]]],
    strict: bool,
) -> tuple[Choice | None, str, str]:
    """Picks the first acceptable translation, or returns the reason the best source was rejected."""
    rejection = ("", "")
    for index, source in enumerate(sources):
        if name not in translations[index]:
            continue
        file, translated = translations[index][name]
        english = source.english().get(name)
        reason = ""
        raw, note = translated.raw, "exact"
        if english is None or english.tag != fork.tag or translated.tag != fork.tag:
            reason, detail = "english-changed", "string type differs"
        elif normalize(translated.body, strict) == normalize(english.body, strict):
            reason, detail = "untranslated", ""
        elif normalize(english.body, strict) == normalize(fork.body, strict):
            if english.body.strip() != fork.body.strip():
                note = "fuzzy"
        elif (
            "AnkiDroid" in english.body
            and normalize(english.body.replace("AnkiDroid", "Hirameki"), strict) == normalize(fork.body, strict)
        ):
            if translated.body.count("AnkiDroid") == english.body.count("AnkiDroid"):
                body = translated.body.replace("AnkiDroid", "Hirameki")
                body_start = translated.raw.rindex(translated.body) if translated.body else len(translated.raw)
                raw = translated.raw[:body_start] + body + translated.raw[body_start + len(translated.body):]
                note = "renamed"
            else:
                reason, detail = "needs-rename", "the translation writes AnkiDroid in its own script"
        else:
            reason, detail = "english-changed", f"upstream: {one_line(english.body)}"
        if not reason:
            body = RESOURCE.match(raw)["body"] or ""
            problem = format_problem(fork, body)
            if problem:
                reason, detail = "format-arguments", problem
        if not reason:
            return Choice(index, file, translated, raw, note), "", ""
        if not rejection[0]:
            rejection = (reason, f"[{source.label}] {detail}".rstrip())
    return None, *rejection


def one_line(text: str, limit: int = 90) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[: limit - 1] + "…"


def remove_resources(text: str, resources: list[Resource], replacements: dict[int, str] | None = None) -> str:
    """Removes resources (with their indentation and line) unless a replacement is given for their start."""
    replacements = replacements or {}
    removing = {r.start for r in resources} - set(replacements)
    pieces, cursor = [], 0
    for resource in sorted(resources, key=lambda r: r.start):
        start, end = resource.start, resource.end
        if resource.start in removing:
            line_start = text.rfind("\n", 0, start) + 1
            if text[line_start:start].strip() == "":
                start = line_start
            line_end = text.find("\n", end)
            if line_end != -1 and text[end:line_end].strip() == "":
                end = line_end + 1
            pieces += [text[cursor:start]]
        else:
            pieces += [text[cursor:start], replacements[resource.start]]
        cursor = end
    pieces.append(text[cursor:])
    return "".join(pieces)


def with_header(text: str) -> str:
    """Replaces Crowdin's "edit on Crowdin" notice with Hirameki's generated-file notice."""
    body = re.sub(r"^\s*<\?xml[^>]*\?>\s*", "", text)
    notice = re.match(r"<!--.*?-->\s*", body, re.S)
    if notice and "AUTOMATICALLY GENERATED" in notice.group():
        body = body[notice.end():]
    return HEADER + body


def sync_locale(
    locale: str,
    sources: list[Source],
    fork_english: dict[str, Resource],
    expected: set[str],
    strict: bool,
) -> LocaleResult:
    result = LocaleResult(locale)
    folder = REPO / FORK_RES / f"values-{locale}"

    # What the fork has today.
    local_texts: dict[str, str] = {}
    for path in sorted(folder.glob("*.xml")):
        text = path.read_text(encoding="utf-8")
        if GENERATED_FILE.match(path.name):
            for resource in parse_resources(text):
                result.before[resource.name] = normalize(resource.body, strict=True)
        else:
            local_texts[path.name] = text
            for resource in parse_resources(text):
                if resource.name in result.local_keys:
                    result.problems.append(
                        f"{resource.name} is defined in both {result.local_keys[resource.name]} and {path.name}"
                    )
                result.local_keys[resource.name] = path.name
                if resource.name not in fork_english:
                    result.problems.append(f"{path.name}: {resource.name} is not a translatable English string")
                elif problem := format_problem(fork_english[resource.name], resource.body):
                    result.problems.append(f"{path.name}: {resource.name} {problem}")

    # Every source's translations, by name.
    source_files = [source.locale_files(locale) for source in sources]
    translations: list[dict[str, tuple[str, Resource]]] = []
    for files in source_files:
        by_name: dict[str, tuple[str, Resource]] = {}
        for file, text in files.items():
            for resource in parse_resources(text):
                by_name.setdefault(resource.name, (file, resource))
        translations.append(by_name)

    names = {name for by_name in translations for name in by_name}
    ai_fill = {n for n, f in result.local_keys.items() if f == AI_FILL_FILE}
    for name in sorted(names):
        fork = fork_english.get(name)
        if fork is None:
            result.skip("not-in-hirameki", name)
            continue
        choice, reason, detail = choose(name, fork, sources, translations, strict)
        if choice is None:
            result.skip(reason, name, detail)
            continue
        if name in result.local_keys and name not in ai_fill:
            result.skip("local", name, result.local_keys[name])
            continue
        if name in ai_fill:
            result.superseded_ai_fill.append(name)
        result.choices[name] = choice

    # Build each generated file from the highest-priority source that has it.
    files = sorted({choice.file for choice in result.choices.values()})
    for file in files:
        base = next(i for i, f in enumerate(source_files) if file in f)
        text = source_files[base][file]
        resources = parse_resources(text)
        kept = {
            r.start: result.choices[r.name].raw
            for r in resources
            if r.name in result.choices
            and result.choices[r.name].source == base
            and result.choices[r.name].file == file
            and result.choices[r.name].resource.start == r.start
        }
        text = remove_resources(text, resources, kept)
        extra = [c.raw for c in result.choices.values() if c.file == file and c.source != base]
        if extra:
            close = text.rindex("</resources>")
            text = text[:close] + "".join(f"    {raw}\n" for raw in extra) + text[close:]
        result.outputs[file] = with_header(text).replace("\r\n", "\n")

    result.removed_files = sorted(
        p.name for p in folder.glob("*.xml") if GENERATED_FILE.match(p.name) and p.name not in result.outputs
    )
    if result.superseded_ai_fill:
        text = local_texts[AI_FILL_FILE]
        drop = [r for r in parse_resources(text) if r.name in result.superseded_ai_fill]
        result.ai_fill_text = remove_resources(text, drop)

    # Check that every file is valid XML and that no name is defined twice.
    for file, text in result.outputs.items():
        try:
            ET.fromstring(text.encode("utf-8"))
        except ET.ParseError as error:
            result.problems.append(f"generated {file} is not valid XML: {error}")
    generated = Counter(r.name for text in result.outputs.values() for r in parse_resources(text))
    result.problems += [f"{n} is generated {c} times" for n, c in generated.items() if c > 1]
    result.problems += [f"{n} is both generated and in {result.local_keys[n]}"
                        for n in generated if n in result.local_keys and n not in result.superseded_ai_fill]

    translated = set(result.choices) | set(result.local_keys)
    result.missing = sorted(expected - translated)
    return result


def write(result: LocaleResult) -> None:
    folder = REPO / FORK_RES / f"values-{result.locale}"
    folder.mkdir(exist_ok=True)
    for file, text in result.outputs.items():
        path = folder / file
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
    for file in result.removed_files:
        (folder / file).unlink()
    if result.ai_fill_text is not None:
        (folder / AI_FILL_FILE).write_text(result.ai_fill_text, encoding="utf-8", newline="\n")


def report(result: LocaleResult, sources: list[Source], fork_english: dict[str, Resource], verbose: bool, list_missing: bool) -> None:
    choices = result.choices.values()
    by_source = Counter(sources[c.source].label for c in choices)
    notes = Counter(c.note for c in choices)
    after = {n: normalize(RESOURCE.match(c.raw)["body"] or "", strict=True) for n, c in result.choices.items()}
    added = [n for n in after if n not in result.before]
    changed = [n for n in after if n in result.before and after[n] != result.before[n]]
    dropped = [n for n in result.before if n not in after and n not in result.local_keys]
    skipped = {reason: len(names) for reason, names in result.skipped.items()}

    print(f"values-{result.locale}: {len(result.choices)} upstream translations "
          f"({', '.join(f'{n} from {label}' for label, n in by_source.items())}; "
          f"{notes['fuzzy']} matched ignoring case/whitespace, {notes['renamed']} renamed to Hirameki)")
    print(f"  not used: {skipped.get('english-changed', 0)} English changed in Hirameki, "
          f"{skipped.get('needs-rename', 0)} only renamed to Hirameki (AnkiDroid is not in Latin script), "
          f"{skipped.get('untranslated', 0)} untranslated upstream, "
          f"{skipped.get('format-arguments', 0)} format argument mismatches, "
          f"{skipped.get('local', 0)} overridden locally, "
          f"{skipped.get('not-in-hirameki', 0)} not in Hirameki")
    print(f"  compared with the current files: {len(added)} added, {len(changed)} updated, {len(dropped)} removed"
          + (f", {len(result.removed_files)} files deleted" if result.removed_files else ""))
    if result.superseded_ai_fill:
        print(f"  {len(result.superseded_ai_fill)} ai-fill.xml entries now translated upstream (removed from ai-fill.xml)")
    print(f"  still in English: {len(result.missing)}" + ("" if list_missing else " (--list-missing to see them)"))
    for problem in result.problems:
        print(f"  PROBLEM: {problem}")

    if verbose:
        for reason in ("english-changed", "needs-rename", "format-arguments"):
            for name, detail in sorted(result.skipped.get(reason, {}).items()):
                print(f"    {reason}: {name}  {detail}")
        for name in sorted(dropped):
            reason = next((r for r, names in result.skipped.items() if name in names), "no longer upstream")
            print(f"    removed ({reason}): {name}")
    if list_missing:
        for name in result.missing:
            print(f"    missing: {name}  = {one_line(fork_english[name].body)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    which = parser.add_mutually_exclusive_group(required=True)
    which.add_argument("--locale", action="append", help="locale folder suffix, e.g. fa or pt-rBR (repeatable)")
    which.add_argument("--all", action="store_true", help="every locale Hirameki already has generated files for")
    parser.add_argument(
        "--source",
        action="append",
        metavar="REF:RES_DIR",
        help=f"where to read translations, highest priority first. Default: {UPSTREAM_REF}:{UPSTREAM_RES}, "
        f"then the commit Hirameki forked from ({UPSTREAM_REF}'s merge base):{FORK_RES}, which still has "
        "strings upstream has since deleted",
    )
    parser.add_argument("--write", action="store_true", help="write the files (default: report only)")
    parser.add_argument("--strict", action="store_true", help="require exactly the same English text")
    parser.add_argument("--verbose", "-v", action="store_true", help="list each string that was not used or removed")
    parser.add_argument("--list-missing", action="store_true", help="list the strings that remain untranslated")
    args = parser.parse_args()

    git = Git()
    specs = args.source or [
        f"{UPSTREAM_REF}:{UPSTREAM_RES}",
        f"{run_git('merge-base', 'HEAD', UPSTREAM_REF)}:{FORK_RES}",
    ]
    sources = []
    for spec in specs:
        ref, _, res = spec.partition(":")
        commit = Git.resolve(ref)
        label = ref if not re.fullmatch(r"[0-9a-f]{40}", ref) else f"fork point {ref[:10]}"
        sources.append(Source(label, commit, res, git))
        print(f"source {len(sources)}: {label} ({commit[:10]}) {res}")

    fork_folders = REPO / FORK_RES
    if args.all:
        locales = sorted(
            p.name.removeprefix("values-")
            for p in fork_folders.glob("values-*")
            if any(GENERATED_FILE.match(f.name) for f in p.glob("*.xml"))
        )
    else:
        locales = args.locale
    fork_english, expected = load_fork_english()

    problems = 0
    for locale in locales:
        if not any(source.locale_files(locale) for source in sources):
            print(f"values-{locale}: no source has translations for this locale, skipped")
            continue
        result = sync_locale(locale, sources, fork_english, expected, args.strict)
        report(result, sources, fork_english, args.verbose, args.list_missing)
        problems += len(result.problems)
        if args.write and not result.problems:
            write(result)
        elif args.write:
            print(f"  not written: fix the problems above first")
    if not args.write:
        print("dry run: nothing written (pass --write)")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
